function design = makeH7Design()
%MAKEH7DESIGN Frozen independent confirmation for simplified B5.

instances = [
    makeItem("D-5-4-H7", "D", 5, 4, 0.025, 160, 16000)
    makeItem("IR-5-4-H7", "IR", 5, 4, 0.025, 160, 16000)
    makeItem("WM-5-3-H7", "WM", 5, 3, 0.020, 100, 10000)
    makeItem("WM-3-5-H7", "WM", 3, 5, 0.040, 144, 14400)
    makeItem("DM2-7-4-H7", "DM2", 7, 4, 0.020, 196, 19600)];
de = struct('F', 0.30, 'CR', 0.50, 'FCategory', 0.75, ...
    'noveltyFractionMin', 0.05, 'noveltyFractionMax', 0.30, ...
    'stagnationHorizon', 10);
design = struct('schema', "mdt.h7-design.v0.1", ...
    'matrixRow', "H7-SIMPLIFIED-CONF", 'instances', instances, ...
    'seeds', 83201:83220, ...
    'algorithms', ["B1", "N2", "B4", "B5"], ...
    'operators', struct('B1', de, 'B4', de, 'B5', de), ...
    'configIds', struct('B1', "B1-004", 'N2', "N2-MV-001", ...
    'B4', "B4-008", 'B5', "B5-FIXED-005"), ...
    'primaryMetric', "AUC_PCR", 'superiorityThreshold', 0.01, ...
    'noninferiorityMargin', -0.005, 'bootstrapReplicates', 20000, ...
    'permutationReplicates', 50000, 'bootstrapSeed', 83300, ...
    'permutationSeed', 83301, 'multiplicityCorrection', "Holm", ...
    'scope', "H7_INDEPENDENT_SIMPLIFIED_CONFIRMATION");
design.expectedSets = numel(instances)*numel(design.seeds);
design.expectedAlgorithmRuns = design.expectedSets*numel(design.algorithms);
end

function item = makeItem(id, family, q, L, rho, N, budget)
item = struct('instanceId', id, 'family', family, 'q', q, 'L', L, ...
    'rho', rho, 'lambda', 1, 'N', N, 'budget', budget, ...
    'archiveCapacity', N);
end
