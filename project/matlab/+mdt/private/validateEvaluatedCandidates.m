function count = validateEvaluatedCandidates(X, obj, con, cfg)
%VALIDATEEVALUATEDCANDIDATES Validate phenotype, objective, and constraint rows.

dimension = 2 + cfg.L;
count = size(X, 1);
if ~isnumeric(X) || count < 1 || size(X, 2) ~= dimension || ...
        ~isnumeric(obj) || ~isequal(size(obj), [count, 2]) || ...
        ~isnumeric(con) || ~isequal(size(con), [count, 2]) || ...
        any(~isfinite(X), 'all') || any(~isfinite(obj), 'all') || ...
        any(~isfinite(con), 'all')
    error('mdt:InvalidEvaluatedCandidates', ...
        'X, obj, and con must be finite aligned matrices with 2+L, 2, and 2 columns.');
end
if any(X(:, 1:2) < 0, 'all') || any(X(:, 1:2) > 1, 'all') || ...
        any(abs(X(:, 3:end)-round(X(:, 3:end))) > 1e-12, 'all') || ...
        any(X(:, 3:end) < 0, 'all') || any(X(:, 3:end) > cfg.q-1, 'all')
    error('mdt:InvalidEvaluatedCandidates', ...
        'X contains an out-of-domain phenotype.');
end
end
