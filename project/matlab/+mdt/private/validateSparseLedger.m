function validateSparseLedger(ledger)
%VALIDATESPARSELEDGER Validate the serialized sparse-ledger invariant.

required = {'schema','backend','stateCount','ranks','counts', ...
    'totalObservations','storedStateCount'};
if ~all(isfield(ledger, required)) || ...
        string(ledger.schema) ~= "mdt.sparse-visit-ledger.v1.0" || ...
        string(ledger.backend) ~= "sparse_sorted_arrays"
    error('mdt:InvalidSparseLedger', ...
        'ledger does not satisfy the sparse-ledger schema.');
end
if ~isscalar(ledger.stateCount) || ~isfinite(ledger.stateCount) || ...
        ledger.stateCount < 1 || ledger.stateCount ~= floor(ledger.stateCount) || ...
        ledger.stateCount > flintmax
    error('mdt:InvalidSparseLedger', 'ledger stateCount is invalid.');
end
ranks = ledger.ranks(:);
counts = ledger.counts(:);
if numel(ranks) ~= numel(counts) || ...
        any(~isfinite(ranks)) || any(ranks < 0) || ...
        any(ranks ~= floor(ranks)) || any(ranks >= ledger.stateCount) || ...
        any(diff(ranks) <= 0) || any(~isfinite(counts)) || ...
        any(counts < 1) || any(counts ~= floor(counts)) || ...
        ledger.storedStateCount ~= numel(ranks) || ...
        ledger.totalObservations ~= sum(counts)
    error('mdt:InvalidSparseLedger', ...
        'ledger ranks, counts, or summary fields violate invariants.');
end
end
