inputs(2) = struct('role', "input_contract", ...
    'source_revision', "generated-from-frozen-run-config", ...
    'path', "input_contract.json", ...
    'sha256', sha256File(fullfile(runDir, 'input_contract.json')));
end

function files = collectSources(projectRoot)
source = [dir(fullfile(projectRoot, 'matlab', '+mdt', '**', '*.m')); ...
    dir(fullfile(projectRoot, 'matlab', 'MDT*.m')); ...
    dir(fullfile(projectRoot, 'tests', '*.m'))];
fixed = [
    ".light/h14/PROJECT_PLAN.md"
    ".light/h14/experiment_matrix.md"
    ".light/h14/preregistration.md"
    ".light/h14/failure-tree.json"
    ".light/h14/failure_tree_report.json"
    ".light/h14/h14_authorization.json"
    ".light/h14/h14_budget_approval.json"
    ".light/h14/h14_formal_resource_budget_v0_1.json"
    ".light/h14/h14_formal_authorization.json"];
fixed = fixed(isfile(fullfile(projectRoot, fixed)));
relative = fixed;
for item = source'
    absolute = string(fullfile(item.folder, item.name));
    relative(end+1, 1) = replace(extractAfter(absolute, ...
        strlength(projectRoot)+1), "\", "/"); %#ok<AGROW>
end
relative = sort(unique(relative));
files = repmat(struct('path', "", 'sha256', ""), numel(relative), 1);
for i = 1:numel(relative)
    files(i).path = relative(i);
    files(i).sha256 = sha256File(fullfile(projectRoot, relative(i)));
end
end

