function code = codeRecord(runDir, sourceManifestHash)
files = [dir(fullfile(runDir, 'code_snapshot', '*.m')); ...
    dir(fullfile(runDir, 'code_snapshot', 'source_manifest.json'))];
records = repmat(struct('path', "", 'sha256', ""), numel(files), 1);
for i = 1:numel(files)
    records(i) = artifactRecord(runDir, ...
        fullfile('code_snapshot', files(i).name));
end
code = struct('commit', "source-manifest:"+sourceManifestHash, ...
    'dirty', true, 'diff_sha256', sourceManifestHash, ...
    'files', records);
end

function inputs = inputRecords(runDir, config)
inputs(1) = struct('role', "data", ...
    'source_revision', "sha256:"+config.oracleSha256, ...
    'path', "oracle_input.json", ...
