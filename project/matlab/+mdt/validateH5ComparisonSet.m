function audit = validateH5ComparisonSet(runs, instanceId)
%VALIDATEH5COMPARISONSET Enforce four-way paired fairness without oracle use.

arguments
    runs (1,1) struct
    instanceId (1,1) string
end
algorithms = ["B0", "B1", "B2", "B4"];
if ~all(isfield(runs, cellstr(algorithms)))
    error('mdt:H5SetMismatch', 'H5 set must contain B0, B1, B2 and B4.');
end
reference = runs.B0;
sameInitialPopulation = true;
sameScheduleSeeds = true;
sameEvaluationBudget = true;
samePopulationSize = true;
sameArchiveCapacity = true;
sameSeed = true;
allTruthFree = true;
algorithmIdentity = true;
for algorithm = algorithms
    run = runs.(char(algorithm));
    sameInitialPopulation = sameInitialPopulation && ...
        isequal(reference.audit.initialPopulation, run.audit.initialPopulation);
    sameScheduleSeeds = sameScheduleSeeds && ...
        isequal(reference.audit.scheduleSeeds, run.audit.scheduleSeeds);
    sameEvaluationBudget = sameEvaluationBudget && ...
        reference.metrics.evaluations == run.metrics.evaluations;
    samePopulationSize = samePopulationSize && ...
        size(reference.audit.initialPopulation, 1) == ...
        size(run.audit.initialPopulation, 1);
    sameArchiveCapacity = sameArchiveCapacity && ...
        reference.finalArchive.capacity == run.finalArchive.capacity;
    sameSeed = sameSeed && reference.audit.seed == run.audit.seed;
    allTruthFree = allTruthFree && ~run.audit.truthUsedBySelection && ...
        ~run.audit.truthUsedByGeneration;
    algorithmIdentity = algorithmIdentity && run.algorithm == algorithm;
end
passed = sameInitialPopulation && sameScheduleSeeds && ...
    sameEvaluationBudget && samePopulationSize && sameArchiveCapacity && ...
    sameSeed && allTruthFree && algorithmIdentity;
if ~passed
    error('mdt:H5SetMismatch', ...
        'H5 comparison set %s failed a fairness or oracle boundary.', instanceId);
end

audit = struct('schema', "mdt.h5-comparison-set-audit.v0.1", ...
    'status', "PASS", ...
    'setId', instanceId + "__seed-" + reference.audit.seed, ...
    'instanceId', instanceId, 'seed', reference.audit.seed, ...
    'sameInitialPopulation', sameInitialPopulation, ...
    'sameScheduleSeeds', sameScheduleSeeds, ...
    'sameEvaluationBudget', sameEvaluationBudget, ...
    'samePopulationSize', samePopulationSize, ...
    'sameArchiveCapacity', sameArchiveCapacity, ...
    'sameSeed', sameSeed, 'allTruthFree', allTruthFree, ...
    'algorithmIdentity', algorithmIdentity);
end
