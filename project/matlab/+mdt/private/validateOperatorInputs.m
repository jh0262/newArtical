function [N, D, lower, upper] = validateOperatorInputs(population, cfg, op, schedule)
%VALIDATEOPERATORINPUTS Validate shared B0/B1 offspring-generation inputs.

D = 2 + cfg.L;
if ~isnumeric(population) || size(population, 2) ~= D || ...
        size(population, 1) < 4 || any(~isfinite(population), 'all')
    error('mdt:InvalidPopulation', ...
        'population must be a finite N-by-(2+L) matrix with N >= 4.');
end
N = size(population, 1);
if any(population(:, 1:2) < 0, 'all') || any(population(:, 1:2) > 1, 'all') || ...
        any(abs(population(:, 3:end)-round(population(:, 3:end))) > 1e-12, 'all') || ...
        any(population(:, 3:end) < 0, 'all') || ...
        any(population(:, 3:end) > cfg.q-1, 'all')
    error('mdt:InvalidPopulation', 'population contains an invalid phenotype.');
end

requiredOp = {'F', 'CR', 'FCategory'};
if ~isstruct(op) || ~all(isfield(op, requiredOp)) || ...
        ~isscalar(op.F) || ~isfinite(op.F) || op.F < 0 || ...
        ~isscalar(op.CR) || ~isfinite(op.CR) || op.CR < 0 || op.CR > 1 || ...
        ~isscalar(op.FCategory) || ~isfinite(op.FCategory) || ...
        op.FCategory < 0 || op.FCategory > 1
    error('mdt:InvalidOperatorConfiguration', 'op contains invalid F, CR, or FCategory.');
end

requiredSchedule = {'donorIndices', 'crossMask', 'roundDraw', 'categoryDraw'};
if ~isstruct(schedule) || ~all(isfield(schedule, requiredSchedule)) || ...
        ~isequal(size(schedule.donorIndices), [N, 3]) || ...
        ~isequal(size(schedule.crossMask), [N, D]) || ...
        ~isequal(size(schedule.roundDraw), [N, D]) || ...
        ~isequal(size(schedule.categoryDraw), [N, D])
    error('mdt:InvalidSchedule', 'schedule dimensions do not match population.');
end
if any(schedule.donorIndices < 1, 'all') || any(schedule.donorIndices > N, 'all') || ...
        any(schedule.donorIndices ~= floor(schedule.donorIndices), 'all') || ...
        any(schedule.roundDraw < 0 | schedule.roundDraw >= 1, 'all') || ...
        any(schedule.categoryDraw < 0 | schedule.categoryDraw >= 1, 'all')
    error('mdt:InvalidSchedule', 'schedule contains invalid indices or random draws.');
end
for i = 1:N
    donors = schedule.donorIndices(i, :);
    if numel(unique(donors)) ~= 3 || any(donors == i)
        error('mdt:InvalidSchedule', 'donors must be distinct and exclude the target.');
    end
end

lower = [0, 0, zeros(1, cfg.L)];
upper = [1, 1, (cfg.q-1)*ones(1, cfg.L)];
end

