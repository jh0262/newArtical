function summary = runH9FunctionalVerification()
%RUNH9FUNCTIONALVERIFICATION Reproduce H9 equivalence and scaling evidence.

cfg = mdt.makeInstance("D", 3, 3, 0.05, 1);
op = makeOperator();
N = 20;
budget = 80;
capacity = 20;
baseline = mdt.runOptimizer("B5S", cfg, op, 1909, N, budget, capacity);
spec = struct( ...
    'continuousLower', [0, 0], ...
    'continuousUpper', [1, 1], ...
    'discreteCardinalities', cfg.q*ones(1, cfg.L), ...
    'orderedDiscreteCount', min(2, cfg.L), ...
    'constraintScales', [1, 0.5-cfg.rho]);
actual = mdt.runB5SparseBlackBox( ...
    @(X) mdt.evaluate(X, cfg), spec, op, 1909, N, budget, capacity);

equivalence = struct();
equivalence.initialPopulation = isequaln(actual.audit.initialPopulation, ...
    baseline.audit.initialPopulation);
equivalence.scheduleSeeds = isequaln(actual.audit.scheduleSeeds, ...
    baseline.audit.scheduleSeeds);
equivalence.finalPopulation = isequaln(actual.finalPopulation, ...
    baseline.finalPopulation);
equivalence.finalArchive = isequaln(actual.finalArchive, baseline.finalArchive);
equivalence.noveltyFractionTimeline = isequaln( ...
    actual.audit.noveltyFractionTimeline, ...
    baseline.audit.noveltyFractionTimeline);
equivalence.noveltyInjectionCountTimeline = isequaln( ...
    actual.audit.noveltyInjectionCountTimeline, ...
    baseline.audit.noveltyInjectionCountTimeline);
equivalence.newFeasibleDiscreteStateTimeline = isequaln( ...
    actual.audit.newFeasibleDiscreteStateTimeline, ...
    baseline.audit.newFeasibleDiscreteStateTimeline);
equivalence.visitLedgerStoredStateCount = ...
    actual.audit.visitLedgerStoredStateCount == ...
    baseline.audit.visitLedgerStoredStateCount;
equivalence.seenFeasibleDiscreteStatesFinal = ...
    actual.audit.seenFeasibleDiscreteStatesFinal == ...
    baseline.audit.seenFeasibleDiscreteStatesFinal;
equivalence.allPassed = all(structfun(@(value) logical(value), equivalence));

largeSpec = struct( ...
    'continuousLower', [0, 0], ...
    'continuousUpper', [1, 1], ...
    'discreteCardinalities', [1000, 1000, 1000, 1000], ...
    'orderedDiscreteCount', 2, ...
    'constraintScales', 1);
largeResult = mdt.runB5SparseBlackBox( ...
    @(X) largeEvaluator(X, largeSpec.discreteCardinalities), ...
    largeSpec, op, 2909, 20, 100, 25);
largeInfo = whos('largeResult');
largeQ = struct();
largeQ.discreteStateCount = largeResult.audit.discreteStateCount;
largeQ.evaluatorCalls = largeResult.audit.evaluatorCalls;
largeQ.visitLedgerStoredStateCount = ...
    largeResult.audit.visitLedgerStoredStateCount;
largeQ.seenFeasibleDiscreteStatesFinal = ...
    largeResult.audit.seenFeasibleDiscreteStatesFinal;
largeQ.truthUsed = largeResult.audit.truthUsed;
largeQ.resultBytes = largeInfo.bytes;
largeQ.hasDenseVisitCounts = isfield(largeResult.audit, 'denseVisitCounts');
largeQ.validFinalPopulation = validPopulation( ...
    largeResult.finalPopulation.X, largeSpec);
largeQ.allPassed = largeQ.evaluatorCalls == 100 && ...
    largeQ.visitLedgerStoredStateCount <= 100 && ...
    largeQ.seenFeasibleDiscreteStatesFinal <= 100 && ...
    ~largeQ.truthUsed && ~largeQ.hasDenseVisitCounts && ...
    largeQ.validFinalPopulation;

replayA = mdt.runB5SparseBlackBox( ...
    @(X) largeEvaluator(X, largeSpec.discreteCardinalities), ...
    largeSpec, op, 3909, 12, 60, 20);
replayB = mdt.runB5SparseBlackBox( ...
    @(X) largeEvaluator(X, largeSpec.discreteCardinalities), ...
    largeSpec, op, 3909, 12, 60, 20);
replayC = mdt.runB5SparseBlackBox( ...
    @(X) largeEvaluator(X, largeSpec.discreteCardinalities), ...
    largeSpec, op, 3910, 12, 60, 20);
determinism = struct();
determinism.sameSeedPopulation = isequaln( ...
    replayA.finalPopulation, replayB.finalPopulation);
determinism.sameSeedArchive = isequaln( ...
    replayA.finalArchive, replayB.finalArchive);
determinism.sameSeedTrace = isequaln(replayA.trace, replayB.trace);
determinism.sameSeedAudit = isequaln(replayA.audit, replayB.audit);
determinism.differentSeedInitialPopulation = ~isequaln( ...
    replayA.audit.initialPopulation, replayC.audit.initialPopulation);
determinism.allPassed = all(structfun(@(value) logical(value), determinism));

summary = struct();
summary.schema = "mdt.h9-functional-verification.v1.0";
summary.claimScope = "functional equivalence, deterministic replay, and sparse large-Q execution only";
summary.matlabVersion = string(version);
summary.computer = string(computer);
summary.equivalence = equivalence;
summary.largeQ = largeQ;
summary.determinism = determinism;
summary.allPassed = equivalence.allPassed && largeQ.allPassed && ...
    determinism.allPassed;
end

function op = makeOperator()
op = struct('F', 0.3, 'CR', 0.5, 'FCategory', 0.75, ...
    'noveltyFractionMin', 0.05, 'noveltyFractionMax', 0.30, ...
    'stagnationHorizon', 10);
end

function [obj, con] = largeEvaluator(X, cardinalities)
continuous = X(:, 1:2);
normalizedDiscrete = X(:, 3:end)./(cardinalities-1);
obj = [sum((continuous-0.25).^2, 2) + ...
    0.01*sum(normalizedDiscrete, 2), ...
    sum((continuous-0.75).^2, 2) + ...
    0.01*sum(1-normalizedDiscrete, 2)];
con = max(sum(continuous, 2)-1.5, 0);
end

function valid = validPopulation(X, spec)
C = numel(spec.continuousLower);
valid = all(X(:, 1:C) >= spec.continuousLower, 'all') && ...
    all(X(:, 1:C) <= spec.continuousUpper, 'all') && ...
    all(X(:, C+1:end) == round(X(:, C+1:end)), 'all');
for j = 1:numel(spec.discreteCardinalities)
    valid = valid && all(X(:, C+j) >= 0) && ...
        all(X(:, C+j) < spec.discreteCardinalities(j));
end
end
