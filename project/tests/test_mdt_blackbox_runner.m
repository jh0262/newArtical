tests = functiontests(localfunctions);
end

function testTruthFreeRunnerMatchesBenchmarkSearchState(testCase)
cfg = mdt.makeInstance("D", 3, 3, 0.05, 1);
op = makeOperator();
seed = 1909;
N = 20;
budget = 80;
capacity = 20;
baseline = mdt.runOptimizer("B5S", cfg, op, seed, N, budget, capacity);
spec = makeLegacySpec(cfg);

actual = mdt.runB5SparseBlackBox( ...
    @(X) mdt.evaluate(X, cfg), spec, op, seed, N, budget, capacity);

verifyEqual(testCase, actual.audit.truthUsed, false);
verifyEqual(testCase, actual.audit.initialPopulation, ...
    baseline.audit.initialPopulation);
verifyEqual(testCase, actual.audit.scheduleSeeds, ...
    baseline.audit.scheduleSeeds);
verifyEqual(testCase, actual.finalPopulation, baseline.finalPopulation);
verifyEqual(testCase, actual.finalArchive, baseline.finalArchive);
verifyEqual(testCase, actual.audit.noveltyFractionTimeline, ...
    baseline.audit.noveltyFractionTimeline);
verifyEqual(testCase, actual.audit.noveltyInjectionCountTimeline, ...
    baseline.audit.noveltyInjectionCountTimeline);
verifyEqual(testCase, actual.audit.newFeasibleDiscreteStateTimeline, ...
    baseline.audit.newFeasibleDiscreteStateTimeline);
verifyEqual(testCase, actual.audit.visitLedgerStoredStateCount, ...
    baseline.audit.visitLedgerStoredStateCount);
verifyEqual(testCase, actual.audit.seenFeasibleDiscreteStatesFinal, ...
    baseline.audit.seenFeasibleDiscreteStatesFinal);
end

function testHeterogeneousQ1e12CompletesWithSparseStorage(testCase)
spec = struct( ...
    'continuousLower', [0, 0], ...
    'continuousUpper', [1, 1], ...
    'discreteCardinalities', [1000, 1000, 1000, 1000], ...
    'orderedDiscreteCount', 2, ...
    'constraintScales', 1);
N = 20;
budget = 100;
actual = mdt.runB5SparseBlackBox( ...
    @syntheticEvaluator, spec, makeOperator(), 2909, N, budget, 25);

verifyEqual(testCase, actual.metrics.evaluations, budget);
verifyEqual(testCase, actual.audit.evaluatorCalls, budget);
verifyEqual(testCase, actual.audit.discreteStateCount, 1e12);
verifyEqual(testCase, actual.audit.truthUsed, false);
verifyLessThanOrEqual(testCase, ...
    actual.audit.visitLedgerStoredStateCount, budget);
verifyLessThanOrEqual(testCase, ...
    actual.audit.seenFeasibleDiscreteStatesFinal, budget);
verifyFalse(testCase, isfield(actual.audit, 'denseVisitCounts'));
X = actual.finalPopulation.X;
verifyGreaterThanOrEqual(testCase, X(:, 1:2), zeros(size(X, 1), 2));
verifyLessThanOrEqual(testCase, X(:, 1:2), ones(size(X, 1), 2));
verifyEqual(testCase, X(:, 3:end), round(X(:, 3:end)));
for j = 1:numel(spec.discreteCardinalities)
    verifyGreaterThanOrEqual(testCase, X(:, 2+j), zeros(size(X, 1), 1));
    verifyLessThan(testCase, X(:, 2+j), ...
        spec.discreteCardinalities(j)*ones(size(X, 1), 1));
end
end

function testDeterministicReplayAndDifferentSeedControl(testCase)
spec = struct( ...
    'continuousLower', [-1, 0], ...
    'continuousUpper', [2, 3], ...
    'discreteCardinalities', [7, 11, 5], ...
    'orderedDiscreteCount', 2, ...
    'constraintScales', 1);
op = makeOperator();
a = mdt.runB5SparseBlackBox(@syntheticEvaluator, spec, op, 3909, 12, 60, 20);
b = mdt.runB5SparseBlackBox(@syntheticEvaluator, spec, op, 3909, 12, 60, 20);
c = mdt.runB5SparseBlackBox(@syntheticEvaluator, spec, op, 3910, 12, 60, 20);

verifyEqual(testCase, deterministicState(a), deterministicState(b));
verifyNotEqual(testCase, a.audit.initialPopulation, c.audit.initialPopulation);
end

function testInvalidEvaluatorOutputIsRejected(testCase)
spec = struct( ...
    'continuousLower', [0, 0], ...
    'continuousUpper', [1, 1], ...
    'discreteCardinalities', [3, 3], ...
    'orderedDiscreteCount', 2, ...
    'constraintScales', 1);
verifyError(testCase, @() mdt.runB5SparseBlackBox( ...
    @invalidEvaluator, spec, makeOperator(), 4909, 8, 16, 10), ...
    'mdt:InvalidBlackBoxEvaluation');
end

function op = makeOperator()
op = struct('F', 0.3, 'CR', 0.5, 'FCategory', 0.75, ...
    'noveltyFractionMin', 0.05, 'noveltyFractionMax', 0.30, ...
    'stagnationHorizon', 10);
end

function spec = makeLegacySpec(cfg)
spec = struct( ...
    'continuousLower', [0, 0], ...
    'continuousUpper', [1, 1], ...
    'discreteCardinalities', cfg.q*ones(1, cfg.L), ...
    'orderedDiscreteCount', min(2, cfg.L), ...
    'constraintScales', [1, 0.5-cfg.rho]);
end

function [obj, con] = syntheticEvaluator(X)
continuous = X(:, 1:2);
discrete = X(:, 3:end);
normalizedDiscrete = discrete ./ max(1, max(discrete, [], 1));
obj = [sum((continuous-0.25).^2, 2) + 0.01*sum(normalizedDiscrete, 2), ...
    sum((continuous-0.75).^2, 2) + 0.01*sum(1-normalizedDiscrete, 2)];
con = max(sum(continuous, 2)-2.5, 0);
end

function [obj, con] = invalidEvaluator(X)
obj = NaN(size(X, 1), 2);
con = zeros(size(X, 1), 1);
end

function value = deterministicState(result)
value = struct( ...
    'metrics', rmfield(result.metrics, 'runtimeSeconds'), ...
    'trace', result.trace, ...
    'finalPopulation', result.finalPopulation, ...
    'finalArchive', result.finalArchive, ...
    'audit', result.audit);
end
