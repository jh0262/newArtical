function summary = runH14ControlledBatch(outputDir, mode)
%RUNH14CONTROLLEDBATCH Execute/resume H14 preflight; formal is fail-closed.

arguments
    outputDir (1,1) string
    mode (1,1) string {mustBeMember(mode, ["formal", "preflight"])}
end
if strlength(outputDir) == 0
    error('mdt:InvalidOutputDirectory', 'outputDir must be nonempty.');
end
projectRoot = string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
formalPerformanceRun = mdt.h14FormalPerformanceFlag(mode);
design = mdt.makeH14Design();
if mode == "formal"
    authorizationDecision = assertFormalAuthorized(design, projectRoot);
    design.formalStartAuthorized = authorizationDecision.startAuthorized;
else
    design = makePreflightDesign(design);
end
matrix = mdt.makeH14RunMatrix(design);
initializeOrValidateBatch(outputDir, mode, design, matrix, projectRoot);
sourceFiles = jsondecode(fileread(fullfile(outputDir, ...
    'source_manifest.json'))).files;
rows = makeResultTable(height(matrix));
completedRuns = 0;
failedRuns = 0;
resumedRuns = 0;
startedAt = localNow();

cachedLandscapeId = "";
benchmark = struct();
oracle = struct();
oraclePath = "";
oracleSha256 = "";
for rowIndex = 1:height(matrix)
    item = matrix(rowIndex, :);
    if item.landscapeUnitId ~= cachedLandscapeId
        [benchmark, oracle] = mdt.makeH14ControlledBenchmark( ...
            item.Q, item.stateLayout, item.componentsPerState, ...
            item.landscapeSeed);
        [oraclePath, oracleSha256] = ensureOracle( ...
            outputDir, item, oracle);
        cachedLandscapeId = item.landscapeUnitId;
    end
    runBase = fullfile(outputDir, 'runs', item.executionRow, ...
        "land-"+item.landscapeSeed, "algseed-"+item.algorithmSeed, ...
        lower(item.algorithm));
    [found, stored, storedDir, nextAttempt] = findCompletedRun(runBase);
    if found
        rows(rowIndex, :) = summaryRow(stored, storedDir);
        completedRuns = completedRuns+1;
        resumedRuns = resumedRuns+1;
        continue;
    end

    attemptDir = fullfile(runBase, "attempt-"+nextAttempt);
    config = makeRunConfig(item, design, mode, nextAttempt, ...
        oraclePath, oracleSha256);
    runStartedAt = localNow();
    try
        op = design.operators.(char(item.algorithm));
        result = mdt.runBlackBoxComparator(item.algorithm, ...
            benchmark.evaluator, benchmark.variableSpec, op, ...
            item.algorithmSeed, item.populationSize, item.budget, ...
            design.archiveCapacity);
        runEndedAt = localNow();
        resultSummary = summarizeResult(result, benchmark, oracle, ...
            item, nextAttempt, runStartedAt, runEndedAt, ...
            formalPerformanceRun);
        writeCompletedBundle(attemptDir, config, result, ...
            resultSummary, benchmark, sourceFiles, projectRoot, outputDir);
        rows(rowIndex, :) = summaryRow(resultSummary, attemptDir);
        completedRuns = completedRuns+1;
    catch errorRecord
        writeFailureBundle(attemptDir, config, errorRecord, ...
            sourceFiles, runStartedAt, localNow(), projectRoot, outputDir);
        rows(rowIndex, :) = failedRow(item, nextAttempt, attemptDir);
        failedRuns = failedRuns+1;
    end
    writetable(rows(1:rowIndex, :), ...
        fullfile(outputDir, 'h14_progress.csv'));
end

writetable(rows, fullfile(outputDir, 'h14_results.csv'));
status = "COMPLETE_FORMAL";
if ~formalPerformanceRun
    status = "COMPLETE_PREFLIGHT";
end
if failedRuns > 0
    status = "INCOMPLETE_FORMAL";
    if ~formalPerformanceRun
        status = "INCOMPLETE_PREFLIGHT";
    end
end
batchManifest = struct('schema', "mdt.h14-batch-manifest.v0.1", ...
    'mode', mode, 'status', status, 'startedAt', startedAt, ...
    'updatedAt', localNow(), 'expectedRuns', height(matrix), ...
    'completedRuns', completedRuns, 'failedRuns', failedRuns, ...
    'resumedRuns', resumedRuns, ...
    'formalPerformanceRun', formalPerformanceRun, ...
    'claimScope', claimScope(formalPerformanceRun));
writeJsonAtomic(fullfile(outputDir, 'batch_manifest.json'), batchManifest);
summary = struct('schema', "mdt.h14-batch-summary.v0.1", ...
    'mode', mode, 'status', status, 'outputDir', outputDir, ...
    'expectedRuns', height(matrix), 'completedRuns', completedRuns, ...
    'failedRuns', failedRuns, 'resumedRuns', resumedRuns, ...
    'formalPerformanceRun', formalPerformanceRun);
end

function decision = assertFormalAuthorized(design, projectRoot)
if ~design.formalPerformanceAuthorized
    error('mdt:H14FormalStartNotAuthorized', ...
        'The H14 formal design has not been approved.');
end
decision = mdt.validateH14FormalAuthorization(projectRoot);
if ~decision.startAuthorized
    error('mdt:H14FormalStartNotAuthorized', ...
        ['The H14 budget and release preparation are approved, but ', ...
        'the 6720-run execution start has not been authorized.']);
end
end

function design = makePreflightDesign(design)
design.status = "PREFLIGHT_ONLY";
design.formalPerformanceAuthorized = false;
design.formalStartAuthorized = false;
design.landscapeSeeds = design.landscapeSeeds(1);
design.algorithmSeeds = design.algorithmSeeds(1);
design.populationSize = 20;
design.archiveCapacity = 20;
design.budget = 100;
cellCount = numel(design.mainCardinalities)* ...
    numel(design.mainLayouts)*numel(design.componentsPerState)+ ...
    numel(design.componentsPerState);
design.expectedMainRuns = 36;
design.expectedBoundaryRuns = 6;
design.expectedFormalRuns = cellCount*numel(design.algorithms);
design.claimBoundary = ...
    "Preflight only; outputs cannot support algorithm ranking.";
end

function initializeOrValidateBatch(outputDir, mode, design, matrix, projectRoot)
configPath = fullfile(outputDir, 'batch_config.json');
if isfolder(outputDir)
    if ~isfile(configPath)
        error('mdt:H14OutputCollision', ...
            'Existing output directory lacks batch_config.json.');
    end
    existing = jsondecode(fileread(configPath));
    if string(existing.mode) ~= mode || ...
            string(existing.design.schema) ~= design.schema || ...
            double(existing.design.populationSize) ~= design.populationSize || ...
            double(existing.design.budget) ~= design.budget || ...
            ~isequal(string(existing.design.algorithms(:)'), ...
            design.algorithms)
        error('mdt:H14ResumeIdentityMismatch', ...
            'Existing H14 output does not match the executable design.');
    end
    return;
end
if isfile(outputDir)
    error('mdt:H14OutputCollision', ...
        'Output path already exists as a file.');
end
mkdir(outputDir);
mkdir(fullfile(outputDir, 'runs'));
mkdir(fullfile(outputDir, 'landscapes'));
writeJsonAtomic(configPath, struct('schema', ...
    "mdt.h14-batch-config.v0.1", 'mode', mode, 'design', design));
writetable(matrix, fullfile(outputDir, 'run_matrix.csv'));
sourceManifest = struct('schema', "mdt.source-manifest.v1.0", ...
    'files', collectSources(projectRoot));
writeJsonAtomic(fullfile(outputDir, 'source_manifest.json'), sourceManifest);
end

function [relativePath, hash] = ensureOracle(outputDir, item, oracle)
relativePath = replace(fullfile('landscapes', item.executionRow, ...
    "land-"+item.landscapeSeed, 'oracle.json'), "\", "/");
path = fullfile(outputDir, relativePath);
parent = fileparts(path);
if ~isfolder(parent)
    mkdir(parent);
end
if isfile(path)
    stored = jsondecode(fileread(path));
    storedCenters = double(stored.centers);
    if numel(storedCenters) == numel(oracle.centers)
        % MATLAB JSON decoding collapses a 1-by-d numeric matrix to d-by-1.
        % Restore the benchmark-defined matrix shape before drift checking.
        storedCenters = reshape(storedCenters, size(oracle.centers));
    end
    if ~isequaln(storedCenters, oracle.centers) || ...
            ~isequal(double(stored.allowedStates(:)), ...
            oracle.allowedStates(:))
        error('mdt:H14OracleDrift', ...
            'Stored landscape oracle differs from deterministic regeneration.');
    end
else
    writeJsonAtomic(path, oracle);
end
hash = sha256File(path);
end

function config = makeRunConfig(item, design, mode, attempt, ...
    oraclePath, oracleSha256)
seedRole = "randomness_estimation";
if mode == "preflight"
    seedRole = "fixed_repro";
end
config = struct('schema', "mdt.h14-run-config.v0.1", ...
    'runId', item.runId, 'pairId', item.pairId, ...
    'landscapeUnitId', item.landscapeUnitId, ...
    'matrixRow', item.executionRow, 'Q', item.Q, ...
    'stateLayout', item.stateLayout, ...
    'componentsPerState', item.componentsPerState, ...
    'landscapeSeed', item.landscapeSeed, ...
    'algorithmSeed', item.algorithmSeed, ...
    'seedRole', seedRole, ...
    'seedStructure', "algorithm_seed_nested_within_landscape_seed", ...
    'algorithm', item.algorithm, 'populationSize', item.populationSize, ...
    'budget', item.budget, 'archiveCapacity', design.archiveCapacity, ...
    'mode', mode, 'attempt', attempt, ...
    'primaryMetric', design.primaryMetric, ...
    'analysisUnit', design.analysisUnit, ...
    'oraclePath', oraclePath, 'oracleSha256', oracleSha256, ...
    'formalPerformanceRun', mdt.h14FormalPerformanceFlag(mode));
end

function item = summarizeResult(result, benchmark, oracle, matrixItem, ...
    attempt, executionStartedAt, executionEndedAt, formalPerformanceRun)
if result.audit.evaluatorCalls ~= matrixItem.budget
    error('mdt:H14NfeViolation', ...
        'Actual evaluator calls differ from the execution budget.');
end
if result.audit.truthUsed || result.audit.truthUsedBySelection || ...
        result.audit.truthUsedByGeneration
    error('mdt:H14TruthFirewallViolation', ...
        'Algorithm-side truth use invalidates the run.');
end
population = result.finalPopulation;
if any(~isfinite(population.X), 'all') || ...
        any(~isfinite(population.obj), 'all') || ...
        any(~isfinite(population.con), 'all')
    error('mdt:H14NonfiniteOutput', 'Final output contains NaN or Inf.');
end
[fscaAuc, fscaAudit] = ...
    mdt.computeH14FeasibleStateCoverageAUC(result, oracle);
[hv, hvAudit] = mdt.computeNormalizedFeasibleHV(population.obj, ...
    population.con, benchmark.idealPoint, benchmark.nadirPoint, ...
    benchmark.hvReferencePoint);
item = struct('schema', "mdt.h14-run-summary.v0.1", ...
    'runId', matrixItem.runId, 'pairId', matrixItem.pairId, ...
    'landscapeUnitId', matrixItem.landscapeUnitId, ...
    'executionRow', matrixItem.executionRow, 'Q', matrixItem.Q, ...
    'stateLayout', matrixItem.stateLayout, ...
    'componentsPerState', matrixItem.componentsPerState, ...
    'landscapeSeed', matrixItem.landscapeSeed, ...
    'algorithmSeed', matrixItem.algorithmSeed, ...
    'algorithm', matrixItem.algorithm, 'actualNfe', ...
    result.audit.evaluatorCalls, 'fscaAuc', fscaAuc, ...
    'finalFeasibleStateCoverage', fscaAudit.finalCoverage, ...
    'normalizedFeasibleHv', hv, 'feasibleNdSize', ...
    hvAudit.nondominatedCount, 'finalFeasibleRate', ...
    result.metrics.finalFeasibleRate, 'runtimeSeconds', ...
    result.metrics.runtimeSeconds, 'status', "completed", ...
    'attempt', attempt, 'truthUsedByAlgorithm', false, ...
    'formalPerformanceRun', formalPerformanceRun, ...
    'executionStartedAt', executionStartedAt, ...
    'executionEndedAt', executionEndedAt);
end

function writeCompletedBundle(runDir, config, result, summary, benchmark, ...
    sourceFiles, projectRoot, outputDir)
if isfolder(runDir) || isfile(runDir)
    error('mdt:H14AttemptCollision', ...
        'Refusing to overwrite an existing run attempt.');
end
mkdir(runDir);
writeJsonAtomic(fullfile(runDir, 'config.json'), config);
writeJsonAtomic(fullfile(runDir, 'environment.json'), environmentInfo());
publicBenchmark = rmfield(benchmark, 'evaluator');
writeJsonAtomic(fullfile(runDir, 'input_contract.json'), struct( ...
    'benchmark', publicBenchmark, 'oraclePath', config.oraclePath, ...
    'oracleSha256', config.oracleSha256, 'sourceFiles', sourceFiles));
writeJsonAtomic(fullfile(runDir, 'result_summary.json'), summary);
writetable(populationTable(result.finalPopulation), ...
    fullfile(runDir, 'predictions.csv'));
writetable(populationTable(result.finalArchive), ...
    fullfile(runDir, 'final_archive.csv'));
writetable(array2table(result.trace, ...
    'VariableNames', cellstr(result.traceColumns)), ...
    fullfile(runDir, 'trace.csv'));
rawSummary = rmfield(summary, {'runtimeSeconds', ...
    'executionStartedAt', 'executionEndedAt'});
writeText(fullfile(runDir, 'raw_metrics.jsonl'), ...
    string(jsonencode(rawSummary))+newline);
guardrails = struct('schema', "mdt.h14-guardrails.v0.1", ...
    'nfeExact', summary.actualNfe == config.budget, ...
    'finiteOutputs', true, 'truthFirewallPassed', ...
    ~summary.truthUsedByAlgorithm, ...
    'formalPerformanceRun', summary.formalPerformanceRun, ...
    'claimScope', claimScope(summary.formalPerformanceRun));
writeJsonAtomic(fullfile(runDir, 'guardrails.json'), guardrails);
testPath = fullfile(projectRoot, 'evidence', 'h14_full_junit.xml');
testEvidence = struct('status', "UNAVAILABLE");
if isfile(testPath)
    testEvidence = struct('status', "AVAILABLE", ...
        'path', "evidence/h14_full_junit.xml", ...
        'sha256', sha256File(testPath));
end
writeJsonAtomic(fullfile(runDir, 'test_evidence.json'), testEvidence);
writeText(fullfile(runDir, 'stdout.log'), ...
    "Completed H14 preflight "+summary.runId+"."+newline);
writeText(fullfile(runDir, 'stderr.log'), "");
writeRunSnapshots(runDir, outputDir, config, projectRoot);
artifacts = completedArtifactMap(runDir);
sourceManifestHash = sha256File(fullfile(outputDir, ...
    'source_manifest.json'));
manifest = struct('schema', "light.run_manifest.v3", ...
    'run_id', summary.runId+"__attempt-"+summary.attempt, ...
    'matrix_row', config.matrixRow, 'matrix_row_id', config.matrixRow, ...
    'pair_id', config.pairId, ...
    'status', "completed", ...
    'termination', struct('reason', "natural_exit", ...
    'exit_code', 0, 'signal', []), ...
    'completion', struct('status', "PASS", ...
    'oracle', ["actualNfe equals the fixed budget", ...
    "truthUsedByAlgorithm is false", "all retained outputs are finite"], ...
    'evidence_artifacts', ["raw_metrics", "predictions", ...
    "test_evidence", "guardrails"]), ...
    'seed', struct('role', config.seedRole, ...
    'value', config.algorithmSeed), ...
    'command', ["matlab", "-batch", ...
    "mdt.runH14ControlledBatch(outputDir,'"+config.mode+"')"], ...
    'config', artifactRecord(runDir, 'config.json'), ...
    'environment', artifactRecord(runDir, 'environment.json'), ...
    'code', codeRecord(runDir, sourceManifestHash), ...
    'inputs', inputRecords(runDir, config), ...
    'started_at', summary.executionStartedAt, ...
    'ended_at', summary.executionEndedAt, ...
    'attempt', config.attempt, 'artifacts', artifacts, ...
    'reproducibility', struct('compare_artifacts', ...
    ["raw_metrics", "predictions"]), ...
    'resultSummarySha256', sha256File(fullfile(runDir, ...
    'result_summary.json')), ...
    'formalPerformanceRun', config.formalPerformanceRun);
writeJsonAtomic(fullfile(runDir, 'manifest.json'), manifest);
end

