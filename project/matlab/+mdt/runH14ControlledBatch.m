    'reproducibility', struct('compare_artifacts', "failure"), ...
    'formalPerformanceRun', config.formalPerformanceRun);
writeJsonAtomic(fullfile(runDir, 'manifest.json'), manifest);
end

function [found, summary, runDir, nextAttempt] = findCompletedRun(runBase)
found = false;
summary = struct();
runDir = "";
attempts = dir(fullfile(runBase, 'attempt-*'));
attempts = attempts([attempts.isdir]);
numbers = zeros(1, numel(attempts));
for i = 1:numel(attempts)
    numbers(i) = sscanf(attempts(i).name, 'attempt-%d');
end
[numbers, order] = sort(numbers, 'descend');
attempts = attempts(order);
for i = 1:numel(attempts)
    candidate = fullfile(attempts(i).folder, attempts(i).name);
    manifestPath = fullfile(candidate, 'manifest.json');
    resultPath = fullfile(candidate, 'result_summary.json');
    if ~isfile(manifestPath) || ~isfile(resultPath)
        continue;
    end
    manifest = jsondecode(fileread(manifestPath));
    if string(manifest.status) ~= "completed"
        continue;
    end
    verifyCompletedManifest(candidate, manifest);
    if string(manifest.resultSummarySha256) ~= sha256File(resultPath)
        error('mdt:H14ResumeArtifactMismatch', ...
            'Completed run summary hash mismatch.');
    end
    found = true;
    summary = jsondecode(fileread(resultPath));
    runDir = string(candidate);
    break;
end
if isempty(numbers)
    nextAttempt = 1;
else
    nextAttempt = max(numbers)+1;
end
end

function verifyCompletedManifest(runDir, manifest)
required = {'config', 'environment', 'code', 'inputs', 'artifacts'};
if ~all(isfield(manifest, required))
    error('mdt:H14ResumeArtifactMismatch', ...
        'Completed manifest is missing required hash records.');
end
assertManifestRecord(runDir, manifest.config, 'config');
assertManifestRecord(runDir, manifest.environment, 'environment');
if ~isfield(manifest.code, 'files') || isempty(manifest.code.files)
    error('mdt:H14ResumeArtifactMismatch', ...
        'Completed manifest has no code snapshot records.');
end
for i = 1:numel(manifest.code.files)
    assertManifestRecord(runDir, manifest.code.files(i), 'code snapshot');
end
if isempty(manifest.inputs)
    error('mdt:H14ResumeArtifactMismatch', ...
        'Completed manifest has no input records.');
end
for i = 1:numel(manifest.inputs)
    assertManifestRecord(runDir, manifest.inputs(i), 'input');
end
names = fieldnames(manifest.artifacts);
for i = 1:numel(names)
    assertManifestRecord(runDir, manifest.artifacts.(names{i}), ...
        "artifact "+string(names{i}));
end
end

function assertManifestRecord(runDir, record, label)
if ~isstruct(record) || ~isfield(record, 'path') || ...
        ~isfield(record, 'sha256')
    error('mdt:H14ResumeArtifactMismatch', ...
        'Malformed %s hash record.', label);
end
relative = replace(string(record.path), "\", "/");
if startsWith(relative, "/") || contains(relative, "../") || ...
        contains(relative, ":")
    error('mdt:H14ResumeArtifactMismatch', ...
        'Unsafe %s path in completed manifest.', label);
end
path = fullfile(runDir, relative);
if ~isfile(path) || string(record.sha256) ~= sha256File(path)
    error('mdt:H14ResumeArtifactMismatch', ...
        '%s file is missing or its SHA256 has changed.', label);
end
end

function row = summaryRow(item, runDir)
row = cell2table({string(item.runId), string(item.executionRow), ...
    double(item.Q), string(item.stateLayout), ...
    double(item.componentsPerState), double(item.landscapeSeed), ...
    double(item.algorithmSeed), string(item.algorithm), ...
    double(item.actualNfe), double(item.fscaAuc), ...
    double(item.finalFeasibleStateCoverage), ...
    double(item.normalizedFeasibleHv), string(item.status), ...
    replace(string(runDir), "\", "/"), double(item.attempt), ...
    logical(item.truthUsedByAlgorithm), ...
    logical(item.formalPerformanceRun)}, ...
    'VariableNames', makeResultTable(1).Properties.VariableNames);
end

function row = failedRow(item, attempt, runDir)
row = cell2table({item.runId, item.executionRow, item.Q, ...
    item.stateLayout, item.componentsPerState, item.landscapeSeed, ...
    item.algorithmSeed, item.algorithm, NaN, NaN, NaN, NaN, ...
    "failed", replace(string(runDir), "\", "/"), attempt, ...
    false, false}, ...
    'VariableNames', makeResultTable(1).Properties.VariableNames);
end

function rows = makeResultTable(count)
rows = table('Size', [count, 17], 'VariableTypes', ...
    {'string','string','double','string','double','double','double', ...
    'string','double','double','double','double','string','string', ...
    'double','logical','logical'}, 'VariableNames', {'runId','executionRow','Q', ...
    'stateLayout','componentsPerState','landscapeSeed','algorithmSeed', ...
    'algorithm','actualNfe','fscaAuc','finalFeasibleStateCoverage', ...
    'normalizedFeasibleHv','status','runDir','attempt', ...
    'truthUsedByAlgorithm','formalPerformanceRun'});
end

function tableValue = populationTable(population)
values = [population.X, population.obj, population.con];
names = ["x"+(1:size(population.X, 2)), ...
    "f"+(1:size(population.obj, 2)), ...
    "g"+(1:size(population.con, 2))];
tableValue = array2table(values, 'VariableNames', cellstr(names));
end

function writeRunSnapshots(runDir, outputDir, config, projectRoot)
copyfile(fullfile(outputDir, config.oraclePath), ...
    fullfile(runDir, 'oracle_input.json'));
snapshotDir = fullfile(runDir, 'code_snapshot');
mkdir(snapshotDir);
copyfile(fullfile(outputDir, 'source_manifest.json'), ...
    fullfile(snapshotDir, 'source_manifest.json'));
sources = [
    "h14FormalPerformanceFlag.m"
    "evaluateH14ExecutionGuard.m"
    "makeH14ControlledBenchmark.m"
    "makeH14Design.m"
    "makeH14RunMatrix.m"
    "runH14ControlledBatch.m"
    "runBlackBoxComparator.m"
    "runB5RandomBlackBox.m"
    "runB5SparseBlackBox.m"
    "validateH14FormalAuthorization.m"];
for i = 1:numel(sources)
    copyfile(fullfile(projectRoot, 'matlab', '+mdt', sources(i)), ...
        fullfile(snapshotDir, sources(i)));
end
end

