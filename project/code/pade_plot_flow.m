function manifest = pade_plot_flow(outDir,opts)
%PADE_PLOT_FLOW Editable FE-clock algorithm diagram; contains no result data.
% The figure is 14.8 cm wide by 15 cm high, suitable for manuscript Fig. 1.
arguments
    outDir (1,1) string
    opts.Language (1,1) string {mustBeMember(opts.Language,["en","zh"])} = "en"
    opts.Visible (1,1) string {mustBeMember(opts.Visible,["on","off"])} = "off"
end
if ~isfolder(outDir), mkdir(outDir); end
settings=pade_defaults(1);
assert(settings.warmupRatio==0.10&&settings.pulseEndRatio==0.90&&settings.stagnationLimit==15,...
    'pade:FlowDefaults','Update the diagram if the frozen time/stagnation defaults change.');
if opts.Language=="zh", font='微软雅黑'; else, font='Arial'; end
fig=figure('Visible',opts.Visible,'Color','w','Units','centimeters',...
    'Position',[2 2 14.8 15],'Renderer','painters');
cleanup=onCleanup(@() closeFigure(fig));
ax=axes(fig,'Position',[0 0 1 1]); axis(ax,[0 1 0 1]); axis(ax,'off'); hold(ax,'on');
english={...
    "Initialise N candidates; box/grid projection Q"+newline+...
    "Evaluate all N candidates; each objective/constraint call adds 1 FE";...
    "Generation start: Deb ordering and stagnation counter W"+newline+...
    "When G>0 or P=1: covariance C, eigenbasis V, entropy H and rho";...
    "Double-lock pulse gate P: 0.10 < current FE/B < 0.90"+newline+...
    "H <= Hcrit AND W >= 15 AND a nonempty low-variance mask";...
    "For each pulse proposal to the worst 20%: check FE<B and FE/B<0.90"+newline+...
    "Low-variance perturbation -> box/grid Q -> evaluate (+1 FE)"+newline+...
    "Deb replacement and immediate update of the best incumbent";...
    "Ordinary trial while FE<B: adaptive current-to-pbest/1 + archive"+newline+...
    "Rotation gate: G>0, current FE/B>0.10, rho>0.20 and U<P_rot";...
    "Original/eigen crossover; spectral amplitude only when G=2"+newline+...
    "Midpoint bound repair -> Q -> trial jitter J (if enabled) -> Q";...
    "Evaluate trial (+1 FE); Deb selection and immediate best update"+newline+...
    "Accepted old parent enters archive; rejected evaluations still cost FE";...
    "End or partial generation: update mu_F, mu_CR and P_rot"+newline+...
    "FE<B: next generation.  FE=B: stop; no extra evaluation"};
chinese={...
    "初始化 N 个候选；执行边界/网格投影 Q"+newline+...
    "评价 N 个候选；每次目标/约束调用均计 1 FE";...
    "代初：Deb 排序并更新停滞计数 W"+newline+...
    "G>0 或 P=1 时计算 C、主轴 V、熵 H 及相关性 rho";...
    "双锁脉冲门 P：0.10 < 当前 FE/B < 0.90"+newline+...
    "H <= Hcrit 且 W >= 15 且低方差子空间非空";...
    "对最差 20% 的每个脉冲提案检查 FE<B 且 FE/B<0.90"+newline+...
    "低方差扰动 -> 边界/网格 Q -> 评价（+1 FE）"+newline+...
    "Deb 替换并立即更新历史最优";...
    "FE<B 时生成普通候选：自适应 current-to-pbest/1 + 归档"+newline+...
    "旋转门：G>0、当前 FE/B>0.10、rho>0.20 且 U<P_rot";...
    "原坐标/主轴交叉；仅 G=2 时加入谱幅调节"+newline+...
    "越界中点修复 -> Q -> trial 离散抖动 J（开启时）-> Q";...
    "评价（+1 FE）；Deb 选择并立即更新历史最优"+newline+...
    "接受时旧父代进入归档；拒绝候选也消耗 FE";...
    "完整代或末尾部分代结束：更新 mu_F、mu_CR 和 P_rot"+newline+...
    "FE<B 则进入下一代；FE=B 则停止，不追加评价"};
if opts.Language=="zh", labels=chinese; else, labels=english; end
centres=[0.919 0.803 0.686 0.558 0.426 0.308 0.193 0.078];
heights=[0.087 0.087 0.090 0.107 0.096 0.090 0.090 0.090];
left=0.065; width=0.79;
for k=1:8
    color=[0.965 0.975 0.985];
    if k==3, color=[0.88 0.94 0.98]; elseif k==4, color=[1.0 0.95 0.86]; end
    rectangle(ax,'Position',[left centres(k)-heights(k)/2 width heights(k)],...
        'Curvature',0.12,'FaceColor',color,'EdgeColor',[0.15 0.20 0.25],'LineWidth',0.8);
    text(ax,left+width/2,centres(k),labels{k},'HorizontalAlignment','center',...
        'VerticalAlignment','middle','FontName',font,'FontSize',7.8,'Interpreter','none');
    if k<8
        arrow(fig,[left+width/2 left+width/2],...
            [centres(k)-heights(k)/2 centres(k+1)+heights(k+1)/2]);
    end
end
% If the double lock or low-variance mask fails, ordinary DE trials continue.
skipX=0.88; gateRight=left+width;
annotation(fig,'line',[gateRight skipX],[centres(3) centres(3)],'LineWidth',0.7);
annotation(fig,'line',[skipX skipX],[centres(3) centres(5)],'LineWidth',0.7);
arrow(fig,[skipX gateRight],[centres(5) centres(5)]);
if opts.Language=="zh", skip='跳过'; yes='开启'; loop='FE < B';
else, skip='skip'; yes='on'; loop='FE < B'; end
text(ax,skipX+0.002,0.676,skip,'FontName',font,'FontSize',7,'Rotation',90,...
    'HorizontalAlignment','right','Interpreter','none');
text(ax,left+width/2+0.014,0.623,yes,'FontName',font,'FontSize',7,'Interpreter','none');
% FE=B ends any pulse batch / ordinary individual loop, not just a full generation.
rectangle(ax,'Position',[0.914 0.242 0.071 0.469],...
    'Curvature',0.10,'FaceColor',[0.97 0.97 0.97],'EdgeColor',[0.55 0.55 0.55],'LineStyle',':');
if opts.Language=="zh"
    guard="每次"+newline+"评价前"+newline+"检查"+newline+"FE<B"+newline+newline+"到 B"+newline+"即停";
    heading='PADE-FE：以实际函数评价次数为时钟';
else
    guard="Before"+newline+"EVERY"+newline+"call:"+newline+"FE<B"+newline+newline+"Stop"+newline+"at B";
    heading='PADE-FE: the clock is actual function evaluations';
end
text(ax,0.9495,0.4765,guard,'HorizontalAlignment','center','VerticalAlignment','middle',...
    'FontName',font,'FontSize',7.3,'Interpreter','none');
text(ax,0.5,0.985,heading,'HorizontalAlignment','center','FontName',font,...
    'FontSize',10,'FontWeight','bold','Interpreter','none');
% Return path is visible; its condition is FE, never a generation-only budget.
annotation(fig,'line',[left 0.025],[centres(8) centres(8)],'LineWidth',0.7);
annotation(fig,'line',[0.025 0.025],[centres(8) centres(2)],'LineWidth',0.7);
arrow(fig,[0.025 left],[centres(2) centres(2)]);
text(ax,0.017,0.455,loop,'Rotation',90,'FontName',font,'FontSize',7,...
    'HorizontalAlignment','center','Interpreter','none');
stem=fullfile(outDir,"00_algorithm_flow_"+opts.Language);
savefig(fig,stem+".fig");
exportgraphics(fig,stem+".png",'Resolution',300,'BackgroundColor','white');
exportgraphics(fig,stem+".pdf",'ContentType','vector','BackgroundColor','white');
caption="PADE-FE v4 control flow from the frozen implementation. B includes initialization, ordinary trials and pulse evaluations. Pulse and rotation gates read the current FE/B clock. Each pulse proposal checks its remaining budget and time window; Q/J/Q denotes grid projection, optional trial jitter, and projection again. Incumbents update immediately after evaluation. The last generation can be partial; no objective call is permitted after FE=B. G=0,1,2 and P/J are the frozen ablation switches.";
if opts.Language=="zh"
    caption="PADE-FE v4 冻结实现的控制流程。预算 B 包含初始化、普通候选与脉冲评价；脉冲与旋转读取当前 FE/B。每个脉冲提案都检查剩余预算和时间窗。Q/J/Q 表示网格投影、可选 trial 抖动及再次投影；评价后立即更新历史最优。末代允许部分执行，到 FE=B 后不再调用目标函数。G=0/1/2 及 P/J 对应冻结消融开关。";
end
writeUtf8(stem+"_caption.txt",caption);
manifest=struct('id','00_algorithm_flow','language',opts.Language,...
    'scope','Control-flow diagram only; no experimental data',...
    'width_cm',14.8,'height_cm',15,'fig',stem+".fig",'png',stem+".png",...
    'pdf',stem+".pdf",'caption',caption,'source_file',which('pade_solve_fe'));
writeUtf8(stem+"_manifest.json",jsonencode(manifest,'PrettyPrint',true));
end

function arrow(fig,x,y)
annotation(fig,'arrow',x,y,'LineWidth',0.7,'HeadLength',3.7,'HeadWidth',3.7);
end

function closeFigure(fig)
if isgraphics(fig), close(fig); end
end

function writeUtf8(path,value)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0,'pade:FlowWrite','Cannot write %s.',path);
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',value);
end
